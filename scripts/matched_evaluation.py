def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", type=Path, default=None,
                        help="write the full report to this path")
    parser.add_argument("--bars", type=int, default=1400)
    args = parser.parse_args()

    rule("PHASE 5 — MATCHED OLYMPUS-VERSUS-KRONOS EVALUATION")
    print("  Every price series below is generated by this repository.")
    print("  No market data, no broker, no real money.")

    # -- 1. the Kronos arm, attempted -----------------------------------
    head("1. Can the genuine Kronos checkpoint be obtained?")
    kronos = probe_kronos()
    for name, value in kronos["detail"].items():
        print(f"  {name:<10} {value}")
    print(f"  source importable   {kronos['source_importable']}")
    print(f"  weights reachable   {kronos['weights_reachable']}")
    obtainable = kronos["source_importable"] and kronos["weights_reachable"]
    print(f"  => the Kronos arm is {'BUILDABLE' if obtainable else 'NOT BUILDABLE'}")

    # -- 2. data --------------------------------------------------------
    head("2. Data")
    bars_by_instrument = {key: series(key, args.bars, seed=SEED + i)
                          for i, key in enumerate(INSTRUMENTS)}
    hashes = {key: dataset_hash(bars)
              for key, bars in bars_by_instrument.items()}
    all_windows, train, validation, test = [], [], [], []
    for key, bars in bars_by_instrument.items():
        windows = make_windows(bars, lookback=LOOKBACK, horizon=HORIZON)
        split = three_way_split(windows, train_fraction=0.6,
                                validation_fraction=0.2)
        all_windows += windows
        train += list(split.train)
        validation += list(split.validation)
        test += list(split.test)
        print(f"  {key:<12} {len(bars):>5} bars  sha256 {hashes[key][:32]}...")
        print(f"  {'':<12} windows train {len(split.train)} / "
              f"validation {len(split.validation)} / test {len(split.test)}"
              f"  embargo {split.embargo_bars} bars")
    test.sort(key=lambda w: (list(w.inputs)[-1].instrument_key,
                             list(w.inputs)[-1].ts_close))
    print(f"  total test windows: {len(test)}")

    # -- 3. the fairness contract ---------------------------------------
    head("3. Fairness contract — identical for every arm")
    strat = strategy()
    timestamps = [list(w.inputs)[-1].ts_close for w in test]
    contract = M.FairnessContract(
        instruments=INSTRUMENTS,
        first_ts=min(timestamps), last_ts=max(timestamps),
        prediction_timestamps_hash=M.timestamps_hash(timestamps),
        n_prediction_timestamps=len(timestamps),
        horizon=HORIZON, lookback=LOOKBACK,
        input_availability_rule=(
            "only bars closing at or before the prediction instant; a "
            "non-final bar cannot enter a window"),
        data_quality_rule=(
            "OHLC coherence enforced at construction; no gaps, duplicates or "
            "non-final bars in the generated series"),
        split_scheme="embargoed three-way temporal split, 60/20/20",
        n_folds=1, embargo_bars=HORIZON,
        cost_model={"round_trip_bps": strat.round_trip_bps,
                    "charged": "on every non-zero position"},
        risk_limits={"max_position": 1, "leverage": 1.0,
                     "instruments": list(INSTRUMENTS)},
        strategy_rules=strat.describe(),
        execution_assumptions=(
            "fills at the anchor close, no slippage model, no partial fills; "
            "identical for every arm, and unrealistic for all of them equally"))
    print(f"  fingerprint  {contract.fingerprint()}")
    for name, value in contract.to_dict().items():
        if name in ("schema_version", "instruments"):
            continue
        text = json.dumps(value, default=str) if isinstance(value, dict) else value
        print(f"  {name:<28} {str(text)[:66]}")

    # -- 4. arms --------------------------------------------------------
    head("4. Arms")
    arms: list[M.ArmResult] = []

    arms.append(run_baseline(M.ArmKind.PERSISTENCE, "persistence",
                             "persistence", train, validation, test,
                             contract=contract, strat=strat))
    arms.append(run_baseline(M.ArmKind.STATISTICAL, "autoregression",
                             "autoregression", train, validation, test,
                             contract=contract, strat=strat))
    arms.append(run_baseline(M.ArmKind.MACHINE_LEARNING,
                             "gradient_boosted_trees",
                             "gradient-boosted trees", train, validation, test,
                             contract=contract, strat=strat))

    arms.append(M.ArmResult(
        spec=M.unavailable(
            M.ArmKind.EXTERNAL_REFERENCE, matched_reference_label(),
            reason=("the genuine official checkpoint cannot be obtained here: "
                    + kronos["detail"].get("weights", "")),
            blockers=matched_reference_blockers()),
        contract_fingerprint=contract.fingerprint()))

    if TU.torch_available():
        selection, tried = select_olympus(train, validation, strat=strat)
    else:
        selection, tried = None, 0
    arms.append(run_olympus(selection, tried, test, contract=contract,
                            strat=strat,
                            input_class=M.InputClass.CANDLES_ONLY,
                            name="olympus-native (candles only)"))
    arms.append(run_olympus(selection, tried, test, contract=contract,
                            strat=strat, input_class=M.InputClass.DERIVED,
                            name="olympus-native (derived features)"))

    arms.append(M.ArmResult(
        spec=M.unavailable(
            M.ArmKind.ENSEMBLE,
            f"olympus + {matched_reference_label()} ensemble",
            reason=("an ensemble needs both members; the reference arm did "
                    "not run"),
            blockers=matched_reference_blockers()),
        contract_fingerprint=contract.fingerprint()))

    for result in arms:
        if result.spec.available:
            print(f"  {result.spec.name:<36} "
                  f"{(str(result.spec.parameters) + ' params'):<14}"
                  f"fit {result.fit_seconds:.2f}s  "
                  f"input {result.spec.input_class.value}")
        else:
            print(f"  {result.spec.name:<36} UNAVAILABLE — "
                  f"{result.spec.availability.reason[:70]}")

    # -- 5. metrics -----------------------------------------------------
    rule("5. FORECAST METRICS")
    available = [a for a in arms if a.spec.available]
    print(forecast_table(available))
    print()
    print(secondary_table(available))

    rule("6. TRADING METRICS")
    print(trading_table(available))

    # -- 7. comparisons -------------------------------------------------
    rule("7. STATISTICAL ANALYSIS")
    olympus_arms = [a for a in available
                    if a.spec.kind is M.ArmKind.OLYMPUS_NATIVE]
    references = [a for a in available
                  if a.spec.kind is not M.ArmKind.OLYMPUS_NATIVE]

    raw: list[M.Comparison] = []
    for arm in olympus_arms:
        for reference in references:
            raw += M.compare_arms(arm, reference,
                                  metrics=("mae", "quantile_loss", "net_return"),
                                  allow_input_advantage=True)
    # Olympus candle-only against Olympus derived: the input-advantage axis.
    if len(olympus_arms) == 2:
        raw += M.compare_arms(olympus_arms[1], olympus_arms[0],
                              metrics=("mae", "quantile_loss", "net_return"),
                              scope="input_advantage",
                              allow_input_advantage=True)
    # And the simple arms against each other, so the field is not only
    # Olympus-versus-everything.
    for i, arm in enumerate(references):
        for reference in references[i + 1:]:
            raw += M.compare_arms(arm, reference,
                                  metrics=("mae", "net_return"))

    regime_raw: list[M.Comparison] = []
    for arm in olympus_arms:
        for reference in references:
            regime_raw += compare_by_regime(arm, reference)

    adjusted = M.adjust_family(raw + regime_raw)
    comparisons = adjusted[:len(raw)]
    regime_comparisons = adjusted[len(raw):]
    print(f"  family size: {len(adjusted)} tests, Holm-adjusted at alpha=0.05")
    print()
    print(comparison_table(comparisons))

    rule("8. REGIME ANALYSIS")
    print(regime_table(available))
    print()
    significant_regimes = [c for c in regime_comparisons if c.significant]
    print(f"  regime-scoped comparisons: {len(regime_comparisons)}, "
          f"significant after correction: {len(significant_regimes)}")
    for comparison in significant_regimes[:12]:
        print(f"    {comparison.scope:<22} {comparison.arm[:26]:<28}"
              f"vs {comparison.reference[:20]:<22}{comparison.metric:<14}"
              f"gain {comparison.gain:+.6f}  p_adj {comparison.p_adjusted:.4f}")

    rule("9. PERIOD AND INSTRUMENT ANALYSIS")
    print(stratified_table(available))

    rule("10. ERROR AND COST ANALYSIS")
    print(error_table(available))

    # -- 11. verdict ----------------------------------------------------
    report = M.MatchedReport(
        contract=contract, arms=tuple(arms), comparisons=tuple(comparisons),
        regime_comparisons=tuple(regime_comparisons),
        dataset_hashes=hashes,
        notes=(
            "every series is generated by this repository; no market data was "
            "read",
            f"kronos probe: {kronos['detail'].get('weights', '')}",
            "the derived-feature Olympus arm and the candle-only arm share "
            "weights and differ only in which outputs they were permitted to "
            "use, so the difference between them is data access alone",
        ))

    rule("11. VERDICT")
    print(f"  arms required        {len(M.REQUIRED_ARMS)}")
    print(f"  arms that ran        {len(report.available_arms)}  "
          f"({', '.join(report.available_arms)})")
    print("  arms that did not:")
    for name, reason in report.missing_arms.items():
        print(f"    {name:<20} {reason[:76]}")
    print()
    print(f"  VERDICT              {report.verdict.value.upper()}")
    print(f"  PROMOTION            {report.promotion.value.upper()}")
    print()
    baseline = report.baseline_verdict
    print("  The sub-question that this environment *can* answer —")
    print("  does the native model beat the simple arms?")
    if not baseline["answerable"]:
        # Not an error: a machine without torch cannot run the Olympus arm, and
        # saying so is a better answer than a traceback or an invented zero.
        print(f"    NOT ANSWERABLE     {baseline['reason']}")
    print(f"    usable comparisons {baseline['n_comparisons']} against "
          f"{', '.join(baseline['references']) or '(none)'}")
    print(f"    significant wins   {len(baseline['significant_wins'])}")
    print(f"    significant losses {len(baseline['significant_losses'])}")
    print(f"    conclusion         {baseline['conclusion']}")
    for loss in baseline["significant_losses"][:8]:
        print(f"      LOSS  {loss['metric']:<14} vs {loss['reference']:<24}"
              f"gain {loss['gain']:+.6f}  p_adj {loss['p_adjusted']:.4f}")

    if args.json:
        args.json.write_text(json.dumps(report.to_dict(), indent=2, default=str))
        print(f"\n  full report written to {args.json}")

    rule("12. KNOWN LIMITATIONS")
    for line in LIMITATIONS:
        print(f"  - {line}")

    return 0


