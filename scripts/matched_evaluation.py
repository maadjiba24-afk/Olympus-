def strategy() -> M.StrategyRule:
    return M.StrategyRule(edge_multiple=1.5, round_trip_bps=4.0)


def record_for(key: str, window, predicted, quantiles, *,
               latency_ms: float | None, abstained: bool,
               strat: M.StrategyRule,
               predicted_volatility: float | None = None,
               direction_probability: float | None = None,
               predicted_regime: str = "") -> M.WindowRecord:
    inputs = list(window.inputs)
    targets = list(window.targets)
    anchor = inputs[-1].close
    realised = math.log(targets[-1].close / anchor)
    path = [math.log(bar.close / anchor) for bar in targets]
    position = strat.apply(predicted)
    net, cost = strat.net(position, realised)
    return M.WindowRecord(
        key=key, instrument=inputs[-1].instrument_key,
        ts=inputs[-1].ts_close, regime=label_regime(inputs),
        realised=realised, predicted=predicted, quantiles=quantiles or {},
        nominal_coverage=0.8 if quantiles else None,
        predicted_volatility=predicted_volatility,
        realised_volatility=realised_volatility(targets),
        direction_probability=direction_probability,
        predicted_regime=predicted_regime,
        realised_drawdown=abs(min(0.0, min(path))),
        abstained=abstained, latency_ms=latency_ms,
        position=position, net_return=net, cost_paid=cost)


def window_key(window) -> str:
    last = list(window.inputs)[-1]
    return f"{last.instrument_key}@{last.ts_close.isoformat()}"


def _parameter_count(model) -> int | None:
    """Baselines expose this as an attribute or a method depending on the
    family. Neither is wrong; assuming one of them is."""
    value = getattr(model, "parameter_count", None)
    if callable(value):
        try:
            return int(value())
        except Exception:                                # noqa: BLE001
            return None
    return int(value) if isinstance(value, (int, float)) else None


def baseline_record(model, window, *, strat) -> M.WindowRecord:
    """One window through a baseline, including the failure path.

    A baseline that raises produces a record with `failed=True` rather than
    being dropped: an arm that answered 40 of 242 windows and an arm that
    answered all 242 are not comparable, and a silently shorter series would
    make the first look like the second.
    """
    bars = list(window.inputs)
    began = time.perf_counter()
    try:
        prediction = model.predict_from_bars(bars)
        latency = (time.perf_counter() - began) * 1000.0
        quantiles = {label: path[-1]
                     for label, path in prediction.log_return_quantiles.items()
                     if path}
        terminal = quantiles.get(prediction.median_label)
        return record_for(window_key(window), window, terminal, quantiles,
                          latency_ms=latency, abstained=False, strat=strat)
    except Exception:                                    # noqa: BLE001
        return M.WindowRecord(
            key=window_key(window), instrument=bars[-1].instrument_key,
            ts=bars[-1].ts_close, regime=label_regime(bars),
            realised=math.log(list(window.targets)[-1].close / bars[-1].close),
            failed=True)


def validation_mae(model, windows, *, strat) -> float | None:
    """Selection score. Computed on **validation only** — a configuration
    chosen on the test split is a configuration that has seen the answer."""
    errors = [r.absolute_error
              for r in (baseline_record(model, w, strat=strat) for w in windows)
              if r.absolute_error is not None]
    return statistics.fmean(errors) if errors else None


#: The configurations each arm is allowed to try, declared up front. Small and
#: written down, because the size of the search is part of the result: an arm
#: that tried forty configurations and an arm that tried one are not comparable
#: on their best number alone.
SEARCH_SPACE: dict[str, tuple[dict, ...]] = {
    "persistence": ({},),
    "autoregression": ({"order": 1}, {"order": 3}, {"order": 5}),
    "gradient_boosted_trees": ({"estimators": 40, "depth": 2},
                               {"estimators": 80, "depth": 3},
                               {"estimators": 150, "depth": 3}),
}

#: The same courtesy for the native model. Three configurations, selected on
#: validation, and the count reported — because the first version of this
#: script gave Olympus one under-trained configuration and measured a +1.4-sigma
#: location bias that a larger model does not have. Under-training one arm is
#: as unfair as over-searching another, and it is easier to do by accident.
OLYMPUS_SEARCH: tuple[dict, ...] = (
    {"d_model": 24, "epochs": 20, "patience": 8},
    {"d_model": 32, "epochs": 60, "patience": 15},
    {"d_model": 48, "epochs": 60, "patience": 15},
)


def run_baseline(kind: M.ArmKind, key: str, name: str, train, validation,
                 test, *, contract, strat) -> M.ArmResult:
    started = time.perf_counter()
    candidates = SEARCH_SPACE.get(key, ({},))
    best, best_score, tried = None, None, 0
    for options in candidates:
        try:
            candidate = B.build_baseline(key, horizon=HORIZON, **options)
            candidate.fit(train)
        except Exception:                                # noqa: BLE001
            continue
        tried += 1
        score = validation_mae(candidate, validation, strat=strat)
        if score is not None and (best_score is None or score < best_score):
            best, best_score = candidate, score
    if best is None:                                     # pragma: no cover
        best = B.build_baseline(key, horizon=HORIZON)
        best.fit(train)
        tried = 1
    model = best
    fit_seconds = time.perf_counter() - started

    records = [baseline_record(model, window, strat=strat) for window in test]

    spec = M.ArmSpec(
        kind=kind, name=name, input_class=M.InputClass.CANDLES_ONLY,
        availability=M.ArmAvailability(available=True),
        parameters=_parameter_count(model),
        model_hash=hashlib.sha256(
            f"{key}|{SEED}|{HORIZON}|{tried}".encode("utf-8")).hexdigest()[:16],
        notes=f"{tried} configuration(s) tried, selected on validation MAE "
              f"{best_score:.6f}" if best_score is not None else
              f"{tried} configuration(s) tried")
    return M.ArmResult(
        spec=spec, contract_fingerprint=contract.fingerprint(),
        records=tuple(records), fit_seconds=fit_seconds,
        forecast=M.forecast_metrics(records),
        trading=M.trading_metrics(records, horizon=HORIZON))


def fit_olympus(train, validation, *, options: dict):
    """Fit one configuration and return `(predictor, record, config, seconds)`."""
    config = MOD.ModelConfig(lookback=LOOKBACK, horizon=HORIZON,
                             d_model=options["d_model"],
                             expert_hidden=options["d_model"])
    started = time.perf_counter()
    trainer = P.Trainer(config, P.TrainingConfig(
        seed=SEED, epochs=options["epochs"], patience=options["patience"]))
    record = trainer.fit(train, validation=validation, dataset_hash="d" * 64)
    seconds = time.perf_counter() - started
    context = SV.build_serving_context(trainer.model, train, config)
    checkpoint = trainer.to_checkpoint(
        record, checkpoint_id=f"phase5-d{options['d_model']}",
        train_start=START, train_end=START + timedelta(days=40),
        feature_names=("log_return",))
    predictor = SV.MultiTaskPredictor(checkpoint, context=context, market="sim")
    return predictor, record, checkpoint, seconds


def olympus_record(predictor, window, *, strat,
                   derived_allowed: bool) -> M.WindowRecord:
    bars = list(window.inputs)
    began = time.perf_counter()
    forecast = predictor.forecast(bars, as_of=bars[-1].ts_close)
    latency = (time.perf_counter() - began) * 1000.0
    declined = forecast.abstention.abstained
    terminal = (forecast.expected_returns[-1]
                if forecast.expected_returns else None)
    quantiles = {label: path[-1]
                 for label, path in (forecast.quantiles or {}).items() if path}
    return record_for(
        window_key(window), window,
        None if declined else terminal, {} if declined else quantiles,
        latency_ms=latency, abstained=declined, strat=strat,
        predicted_volatility=(forecast.predicted_volatility
                              if derived_allowed else None),
        direction_probability=(
            forecast.direction_probabilities.get("up")
            if derived_allowed and forecast.direction_probabilities else None),
        predicted_regime=(
            max(forecast.regime_probabilities.items(), key=lambda kv: kv[1])[0]
            if derived_allowed and forecast.regime_probabilities else ""))


def select_olympus(train, validation, *, strat):
    """Choose the native configuration on **validation only**.

    Returns the fitted predictor, the run record, the checkpoint, the fit time,
    how many configurations were tried and the score that chose it. The count
    travels into the manifest: an arm's best-of-three and an arm's only-attempt
    are different claims about the same number.
    """
    best = None
    for options in OLYMPUS_SEARCH:
        predictor, record, checkpoint, seconds = fit_olympus(
            train, validation, options=options)
        errors = [r.absolute_error for r in
                  (olympus_record(predictor, w, strat=strat,
                                  derived_allowed=True) for w in validation)
                  if r.absolute_error is not None]
        # An arm that declines the whole validation split has no selection
        # score. It is not thereby the best one — it is unselectable.
        score = statistics.fmean(errors) if errors else None
        answered = len(errors)
        if score is None:
            continue
        if best is None or score < best["score"]:
            best = {"predictor": predictor, "record": record,
                    "checkpoint": checkpoint, "seconds": seconds,
                    "score": score, "options": options, "answered": answered}
    return best, len(OLYMPUS_SEARCH)


def run_olympus(selection, tried, test, *, contract, strat,
                input_class: M.InputClass, name: str) -> M.ArmResult:
    """One measurement of the selected native model under one input class.

    The two input classes share the *same weights* and differ only in whether
    the derived outputs — volatility, direction, regime — are permitted. That
    keeps the input-advantage axis a pure data-access difference; refitting per
    class would confound it with training variance.
    """
    if selection is None:
        return M.ArmResult(
            spec=M.unavailable(
                M.ArmKind.OLYMPUS_NATIVE, name,
                reason=("no configuration produced a usable validation score; "
                        "every candidate declined the whole validation split"),
                blockers=("B5",), input_class=input_class),
            contract_fingerprint=contract.fingerprint())

    derived = input_class is not M.InputClass.CANDLES_ONLY
    records = [olympus_record(selection["predictor"], window, strat=strat,
                              derived_allowed=derived) for window in test]
    stats = selection["predictor"].stats()
    record = selection["record"]
    spec = M.ArmSpec(
        kind=M.ArmKind.OLYMPUS_NATIVE, name=name, input_class=input_class,
        availability=M.ArmAvailability(available=True),
        parameters=record.parameters or None,
        model_hash=selection["checkpoint"].content_hash[:16],
        notes=(f"seed {SEED}, d_model {selection['options']['d_model']}, "
               f"{len(record.epochs)} epochs run, best {record.best_epoch}; "
               f"{tried} configurations tried, selected on validation MAE "
               f"{selection['score']:.6f}"))
    return M.ArmResult(
        spec=spec, contract_fingerprint=contract.fingerprint(),
        records=tuple(records), fit_seconds=selection["seconds"],
        forecast=M.forecast_metrics(records, memory_kb=stats.memory_kb),
        trading=M.trading_metrics(records, horizon=HORIZON))


