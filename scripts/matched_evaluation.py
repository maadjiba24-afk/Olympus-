def probe_kronos() -> dict:
    """Try to obtain the genuine official checkpoint. Report what happened.

    Three things are needed and each is checked separately, because they fail
    for different reasons and a single "unavailable" would hide which one.
    """
    report = {"source_importable": False, "weights_reachable": False,
              "licence_readable": False, "detail": {}}

    from olympus.trading import kronos_runtime as KR
    try:
        KR._import_upstream_kronos()
        report["source_importable"] = True
        report["detail"]["source"] = "the upstream package is importable"
    except Exception as error:                           # noqa: BLE001
        report["detail"]["source"] = f"{type(error).__name__}: {error}"

    pin = KR.DEFAULT_PREDICTOR_PIN
    report["detail"]["repo_id"] = pin.repo_id
    report["detail"]["revision"] = getattr(pin, "revision", "") or "(unpinned)"

    import subprocess
    url = f"https://huggingface.co/{pin.repo_id}/resolve/main/config.json"
    try:
        completed = subprocess.run(
            ["curl", "-sS", "-o", "/dev/null", "-w", "%{http_code}",
             "--max-time", "20", url],
            capture_output=True, text=True, timeout=40)
        code = (completed.stdout or "").strip()
        stderr = (completed.stderr or "").strip()
        report["weights_reachable"] = code.startswith("2")
        report["detail"]["weights"] = (
            f"GET {url} -> http={code or 'none'}"
            + (f"; {stderr[:120]}" if stderr else ""))
    except Exception as error:                           # noqa: BLE001
        report["detail"]["weights"] = f"{type(error).__name__}: {error}"

    report["detail"]["licence"] = (
        "the upstream source is MIT (verified by reading the repository's "
        "LICENSE). The *weights* are distributed separately on the model hub "
        "under terms stated on a page this environment cannot reach, so the "
        "weight licence remains unverified — blocker B4")
    return report


