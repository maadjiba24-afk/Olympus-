#!/usr/bin/env python3
"""Phase 5: the matched Olympus-versus-Kronos evaluation.

    python scripts/matched_evaluation.py [--json out.json]

Runs every one of the six required arms that can be built here, under one
fairness contract, and prints the manifest, the metric tables, the regime and
period breakdowns, the statistical analysis and the computed verdict.

**The Kronos arm cannot be built in this environment**, and the script
establishes that by measurement rather than assertion: it attempts the fetch
and reports what came back. That makes the verdict `INSUFFICIENT_EVIDENCE` by
construction, which is one of the six categories Phase 5 permits and is the
honest one. The other five arms still run, because the question "does the
native model beat a simple baseline" *is* answerable here and its answer is
worth having.

Nothing in this script trades real money, reaches a broker or reads market
data. Every price series is generated by this repository.
"""

