def series(key: str, n: int, *, seed: int) -> list[Candle]:
    """A mean-reverting series for one instrument and a trendier one for the
    other. Both are generated here; neither is a market."""
    rng = random.Random(seed)
    trending = key == "SIM:TREND"
    prices, step = [100.0], 0.0
    for i in range(n - 1):
        persistence = 0.90 if trending else 0.25
        drift = 0.00004 if trending else 0.0
        shock = rng.gauss(0.0, 0.0022 if trending else 0.0035)
        step = persistence * step + shock + drift
        prices.append(max(1e-6, prices[-1] * math.exp(step)))
    out = []
    for i, price in enumerate(prices):
        high = price * (1.0 + abs(rng.gauss(0.0, 0.0008)))
        low = price * (1.0 - abs(rng.gauss(0.0, 0.0008)))
        out.append(Candle(instrument_key=key, timeframe="1h",
                          ts_open=START + timedelta(hours=i),
                          ts_close=START + timedelta(hours=i + 1),
                          open=price, high=max(high, price),
                          low=min(low, price), close=price,
                          volume=1000.0 + 400.0 * abs(rng.gauss(0, 1))))
    return out


def dataset_hash(bars) -> str:
    payload = "|".join(f"{b.instrument_key}:{b.ts_close.isoformat()}:"
                       f"{b.open!r}:{b.high!r}:{b.low!r}:{b.close!r}:{b.volume!r}"
                       for b in bars)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def realised_volatility(bars) -> float:
    steps = [math.log(bars[i].close / bars[i - 1].close)
             for i in range(1, len(bars))]
    return statistics.pstdev(steps) if len(steps) > 1 else 0.0


def label_regime(bars) -> str:
    """A cheap, identical regime label for every arm. Terciles of trend
    strength over the window, so no arm gets a better label than another."""
    if len(bars) < 4:
        return Regime.UNKNOWN.value
    trend = math.log(bars[-1].close / bars[0].close)
    dispersion = realised_volatility(bars)
    if dispersion <= 0:
        return Regime.UNKNOWN.value
    ratio = trend / (dispersion * math.sqrt(len(bars)))
    if ratio > 0.5:
        return Regime.TRENDING_UP.value
    if ratio < -0.5:
        return Regime.TRENDING_DOWN.value
    return Regime.RANGING.value


