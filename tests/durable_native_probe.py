"""Owned test observer for actual staging flush/rename ordering.

This is a test helper, not a durability implementation. Every successful path
delegates its actual filesystem calls. Faults are injected only at the selected
staging fsync call. Windows directory sync means fresh held-ancestor checks,
not directory fsync or physical power-loss proof. No candidate import occurs
until a test constructs the observer or requests independent readback.
"""
import os
from pathlib import Path
import stat


MAX_IMAGE = 2 * 1024 * 1024


def native_path(path):
    path = Path(path)
    assert path.is_absolute()
    if os.name == 'nt' and not str(path).startswith('\\\\?\\'):
        return Path('\\\\?\\' + str(path))
    return path


def _id(info):
    assert stat.S_ISREG(info.st_mode) and info.st_nlink == 1
    assert not getattr(info, 'st_file_attributes', 0) & 0x400
    return info.st_dev, info.st_ino


def _read_fd(fd, size):
    assert 0 <= size <= MAX_IMAGE
    offset = os.lseek(fd, 0, os.SEEK_CUR)
    failure = None
    try:
        os.lseek(fd, 0, os.SEEK_SET)
        chunks, remaining = [], size + 1
        while remaining:
            part = os.read(fd, min(remaining, 65536))
            if not part:
                break
            chunks.append(part)
            remaining -= len(part)
        raw = b''.join(chunks)
        assert len(raw) == size
        return raw
    except BaseException as error:
        failure = error
        raise
    finally:
        try:
            os.lseek(fd, offset, os.SEEK_SET)
        except BaseException:
            if failure is None:
                raise


def read_image(path):
    """Independent, bounded, freshly opened read after product ownership closes."""
    from olympus import native_cleanup, vault_storage
    flags = os.O_RDONLY | getattr(os, 'O_BINARY', 0) | getattr(os, 'O_NOFOLLOW', 0)
    fd = os.open(native_path(path), flags)
    failure = None
    try:
        before = vault_storage._file_information(fd)
        identity = _id(before)
        raw = _read_fd(fd, before.st_size)
        after = vault_storage._file_information(fd)
        assert vault_storage._file_identity(before) == vault_storage._file_identity(after)
        return raw, identity
    except BaseException as error:
        failure = error
        raise
    finally:
        owned, fd = fd, None
        native_cleanup.drain([lambda: os.close(owned)], failure)


class NativePublicationProbe:
    """Observe only exact owned targets, with identity and successful-call facts.

    `expected` maps absolute targets to expected bytes, or None when the actual
    generated bytes will be independently verified afterward. In-callback
    assertion failures are retained and asserted again outside public error
    normalization, so an observer defect cannot masquerade as an expected fault.
    """
    def __init__(self, monkeypatch, kind, expected, *, fail_target=None, failure=None):
        from olympus import archive_io, prefs_storage, vault_storage
        assert kind in ('prefs', 'archive')
        assert 1 <= len(expected) <= 8
        self.expected = {Path(path): raw for path, raw in expected.items()}
        assert all(path.is_absolute() for path in self.expected)
        assert all(raw is None or type(raw) is bytes and 0 < len(raw) <= MAX_IMAGE
                   for raw in self.expected.values())
        self.fail_target = None if fail_target is None else Path(fail_target)
        assert (self.fail_target is None) == (failure is None)
        assert self.fail_target is None or self.fail_target in self.expected
        self.failure, self.faults = failure, 0
        self.frames, self.errors, self.directory_syncs = [], [], []
        self.active, self.writing, self.syncing = None, None, None
        self.sequence = 0
        directory_type = prefs_storage._Directory if kind == 'prefs' else vault_storage._Directory
        self.information = vault_storage._file_information
        real_write, real_sync = directory_type._write, directory_type.sync
        real_fsync, real_replace = os.fsync, os.replace

        def checked(condition, message):
            if not condition:
                self.errors.append(message)
                raise AssertionError(message)

        def selected_publish(path, raw, invoke):
            path = Path(path)
            if path not in self.expected:
                return invoke()
            checked(self.active is None, 'nested observed publication')
            checked(type(raw) is bytes and 0 < len(raw) <= MAX_IMAGE, 'unbounded publication')
            wanted = self.expected[path]
            checked(wanted is None or raw == wanted, 'unexpected publication image')
            checked(len(self.frames) < 16, 'publication observation bound')
            frame = {'path': path, 'raw': raw, 'start': self.tick(), 'write': None,
                     'flush': None, 'rename_start': None, 'rename_return': None, 'rename_attempts': [],
                     'syncs': [], 'returned': None}
            self.frames.append(frame)
            self.active = frame
            try:
                result = invoke()
                frame['returned'] = self.tick()
                return result
            finally:
                self.active = None

        if kind == 'prefs':
            original_publish = directory_type.publish
            def publish(directory, name, raw):
                return selected_publish(directory.path / name, raw,
                    lambda: original_publish(directory, name, raw))
            monkeypatch.setattr(directory_type, 'publish', publish)
        else:
            original_publish = archive_io.publish_file
            def publish(path, raw):
                return selected_publish(path, raw, lambda: original_publish(path, raw))
            monkeypatch.setattr(archive_io, 'publish_file', publish)

        def write(directory, fd, raw):
            frame = self.active
            if frame is None:
                return real_write(directory, fd, raw)
            checked(frame['write'] is None and self.writing is None, 'unexpected staging write count')
            checked(Path(directory.path) == frame['path'].parent and raw == frame['raw'],
                    'staging owner/image does not match target')
            record = {'fd': fd, 'identity': _id(self.information(fd)), 'directory': directory}
            frame['write'] = record
            self.writing = frame
            try:
                return real_write(directory, fd, raw)
            finally:
                self.writing = None

        def fsync(fd):
            frame = self.writing
            if frame is not None and fd == frame['write']['fd']:
                info = self.information(fd)
                checked(_id(info) == frame['write']['identity'], 'staging identity changed before flush')
                checked(info.st_size == len(frame['raw']), 'flush did not cover the full staged image')
                checked(frame['flush'] is None, 'duplicate selected staging flush')
                if frame['path'] == self.fail_target:
                    self.faults += 1
                    checked(self.faults == 1, 'selected failed flush was retried')
                    raise self.failure
                result = real_fsync(fd)
                after = self.information(fd)
                checked(_id(after) == frame['write']['identity'] and after.st_size == len(frame['raw']),
                        'successful flush no longer identifies staged image')
                frame['flush'] = self.tick()  # Only after actual fsync returns.
                return result
            result = real_fsync(fd)
            if self.syncing is not None and fd == self.syncing['fd']:
                checked(stat.S_ISDIR(os.fstat(fd).st_mode), 'parent flush was not a directory')
                self.syncing['directory_fsync'] = self.tick()
            return result

        def sync(directory):
            path = Path(directory.path)
            if path not in {target.parent for target in self.expected}:
                return real_sync(directory)
            checked(self.syncing is None, 'nested observed directory sync')
            row = {'path': path, 'fd': directory.fd if directory.win is None else None,
                   'directory_fsync': None, 'returned': None}
            self.syncing = row
            try:
                result = real_sync(directory)
                row['returned'] = self.tick()
                self.directory_syncs.append(row)
                if self.active is not None:
                    self.active['syncs'].append(row)
                return result
            finally:
                self.syncing = None

        def before_rename(frame, identity, raw):
            checked(frame['write'] is not None, 'rename without observed staged write')
            checked(identity == frame['write']['identity'], 'rename uses a different native file')
            checked(raw == frame['raw'], 'rename uses different staged bytes')
            checked(frame['flush'] is not None, 'rename preceded successful staging fsync')
            checked(frame['rename_return'] is None and len(frame['rename_attempts']) < 16,
                    'rename repeated after success or exceeded observation bound')
            attempt = self.tick()
            frame['rename_attempts'].append(attempt)
            if frame['rename_start'] is None:
                frame['rename_start'] = attempt

        def replace(src, dst, *args, **kwargs):
            frame = self.active
            if frame is None:
                return real_replace(src, dst, *args, **kwargs)
            checked(not args and frame['write'] is not None, 'unexpected relative rename call')
            directory = frame['write']['directory']
            checked(Path(dst).name == frame['path'].name and str(dst) == frame['path'].name,
                    'rename destination is not the observed leaf')
            checked(kwargs == {'src_dir_fd': directory.fd, 'dst_dir_fd': directory.fd},
                    'rename did not use the same held parent')
            checked(type(src) is str and Path(src).name == src, 'rename source is not a relative leaf')
            fd = os.open(src, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory.fd)
            primary = None
            try:
                info = self.information(fd)
                before_rename(frame, _id(info), _read_fd(fd, info.st_size))
                result = real_replace(src, dst, **kwargs)
                checked(_id(self.information(fd)) == frame['write']['identity'],
                        'renamed source identity changed')
                frame['rename_return'] = self.tick()
                return result
            except BaseException as error:
                primary = error
                raise
            finally:
                from olympus import native_cleanup
                owned, fd = fd, None
                native_cleanup.drain([lambda: os.close(owned)], primary)

        if os.name == 'nt':
            import msvcrt
            if kind == 'prefs':
                from olympus import prefs_windows as native
            else:
                from olympus import gallery_windows as native
            original_rename = native.rename_same_directory
            def rename(handle, name):
                frame = self.active
                if frame is None:
                    return original_rename(handle, name)
                checked(frame['write'] is not None, 'native rename without staged descriptor')
                fd = frame['write']['fd']
                checked(name == frame['path'].name and msvcrt.get_osfhandle(fd) == handle,
                        'native rename did not receive the flushed held handle')
                info = self.information(fd)
                before_rename(frame, _id(info), _read_fd(fd, info.st_size))
                result = original_rename(handle, name)
                checked(_id(self.information(fd)) == frame['write']['identity'],
                        'native renamed identity changed')
                frame['rename_return'] = self.tick()
                return result
            monkeypatch.setattr(native, 'rename_same_directory', rename)
        else:
            monkeypatch.setattr(os, 'replace', replace)
        monkeypatch.setattr(directory_type, '_write', write)
        monkeypatch.setattr(directory_type, 'sync', sync)
        monkeypatch.setattr(os, 'fsync', fsync)

    def tick(self):
        self.sequence += 1
        assert self.sequence <= 2048
        return self.sequence

    def only(self, path):
        assert self.errors == []
        rows = [row for row in self.frames if row['path'] == Path(path)]
        assert len(rows) == 1
        return rows[0]

    def assert_published(self, path):
        row = self.only(path)
        assert row['start'] < row['flush'] < row['rename_start'] < row['rename_return'] < row['returned']
        assert row['rename_attempts'] and all(row['flush'] < attempt < row['rename_return']
                                              for attempt in row['rename_attempts'])
        barriers = [item for item in row['syncs']
                    if row['rename_return'] < item['returned'] < row['returned']]
        assert barriers
        if os.name != 'nt':
            assert any(item['directory_fsync'] is not None
                       and row['rename_return'] < item['directory_fsync'] < item['returned']
                       for item in barriers)
        raw, identity = read_image(path)
        assert raw == row['raw'] and identity == row['write']['identity']
        return row

    def assert_failed_flush(self, path):
        row = self.only(path)
        assert self.faults == 1 and row['write'] is not None
        assert row['flush'] is None and row['rename_start'] is None
        assert row['rename_return'] is None and row['returned'] is None
        assert row['rename_attempts'] == []
        return row

    def assert_final_barrier_before(self, targets, completion):
        rows = [self.assert_published(path) for path in targets]
        done = self.assert_published(completion)
        last_return = max(row['returned'] for row in rows)
        parent = Path(targets[0]).parent
        assert all(Path(path).parent == parent for path in targets)
        between = [row for row in self.directory_syncs
                   if row['path'] == parent and last_return < row['returned'] < done['start']]
        assert between
        if os.name != 'nt':
            assert any(row['directory_fsync'] is not None
                       and last_return < row['directory_fsync'] < row['returned'] for row in between)
