START = datetime(2027, 3, 1, tzinfo=timezone.utc)
KEY = "SIM:P3"
TF = "1h"

#: The generating process. `PHI` near 1 makes the next step strongly predictable
#: from the last, which is the point: P3 asks whether the pipeline can learn a
#: structure that is definitely there, not whether markets have one.
PHI = 0.97
NOISE = 0.001
#: E[cumulative log return over 3 steps | last step s] = s · (φ + φ² + φ³)
TRUTH_FACTOR = sum(PHI ** k for k in range(1, 4))

SPEC = D.DatasetSpec(instrument_keys=(KEY,), timeframe=TF, lookback=17, horizon=3)
CONFIG = N.NeuralConfig(lookback=17, horizon=3, patch_len=4, d_model=16,
                        n_layers=2, epochs=80, batch_size=64,
                        learning_rate=1e-2)


def bars(prices) -> list[Candle]:
    return [Candle(instrument_key=KEY, timeframe=TF,
                   ts_open=START + timedelta(hours=i),
                   ts_close=START + timedelta(hours=i + 1),
                   open=p, high=p * 1.004, low=p * 0.996, close=p,
                   volume=1000.0 + i)
            for i, p in enumerate(prices)]


def ar1_series(n=1400, seed=5, phi=PHI, noise=NOISE):
    """AR(1) on log steps — a series whose conditional mean is known exactly."""
    rng = random.Random(seed)
    prices, step = [100.0], 0.0
    for _ in range(n - 1):
        step = phi * step + rng.gauss(0.0, noise)
        prices.append(prices[-1] * math.exp(step))
    return prices


def random_walk(n=1400, seed=9, sigma=0.003):
    """No structure at all. The negative control."""
    rng = random.Random(seed)
    prices = [100.0]
    for _ in range(n - 1):
        prices.append(prices[-1] * math.exp(rng.gauss(0.0, sigma)))
    return prices


@pytest.fixture(scope="module")
def fitted():
    """One fit, reused. Training is seconds, not milliseconds."""
    return T.train_neural(bars(ar1_series()), spec=SPEC, config=CONFIG,
                          checkpoint_id="p3-structured", seed=0,
                          clock=FixedClock(START + timedelta(days=90)))


@pytest.fixture(scope="module")
def on_noise():
    return T.train_neural(bars(random_walk()), spec=SPEC, config=CONFIG,
                          checkpoint_id="p3-walk", seed=0,
                          clock=FixedClock(START + timedelta(days=90)))


def median_predictions(result):
    """`(predicted terminal median, realised terminal, true conditional mean)`."""
    model = N.NeuralQuantileModel.from_parameters(result.checkpoint.parameters)
    labels = [quantile_label(q) for q in model.config.quantiles]
    median = labels[model.config.median_index]
    predicted, realised, truth = [], [], []
    for window in result.split.test:
        prediction = model.predict_from_bars(window.inputs)
        if isinstance(prediction, Declined):
            continue
        closes = [b.close for b in window.inputs]
        predicted.append(prediction.log_return_quantiles[median][-1])
        realised.append(window.target_log_returns()[-1])
        truth.append(math.log(closes[-1] / closes[-2]) * TRUTH_FACTOR)
    return predicted, realised, truth


