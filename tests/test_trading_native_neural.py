def test_the_encoder_refuses_a_ragged_patch_grid():
    """Padding the *oldest* bars with zeros would teach the model that history
    began with a flat market."""
    with pytest.raises(ConfigurationError) as exc:
        E.EncoderConfig(lookback=10, patch_len=4)
    assert "ragged final patch" in str(exc.value)


def test_channels_are_scale_free():
    """A model trained on absolute prices learns the price level, which is the
    one thing guaranteed not to generalise."""
    cheap = bars([100.0 * (1.01 ** i) for i in range(20)])
    dear = bars([100_000.0 * (1.01 ** i) for i in range(20)])
    a = E.bars_to_channels(cheap)
    b = E.bars_to_channels(dear)
    assert a[0] == pytest.approx(b[0]), "log returns must not depend on level"


def test_normalisation_uses_the_window_only():
    """Causal because `data.Window` guarantees targets close after inputs — the
    §12.9 failure is normalising over a range that includes the horizon."""
    channels = E.bars_to_channels(bars(ar1_series(60)))
    normalised, stats = E.normalise_window(channels)
    assert len(stats) == len(E.CHANNELS)
    assert statistics.fmean(normalised[0]) == pytest.approx(0.0, abs=1e-9)


def test_a_constant_window_does_not_divide_by_zero():
    channels = E.bars_to_channels(bars([100.0] * 30))
    normalised, _ = E.normalise_window(channels)
    assert all(math.isfinite(v) for column in normalised for v in column)


