"""The neural quantile model — phase P3, learning on synthetic data.

P3's exit condition: the training pipeline converges on a synthetic series with
**known** structure and recovers that structure.

"Recovers" is tested against the truth rather than against a leaderboard. The
generating process here is an AR(1) on log steps, so the conditional expectation
of the cumulative log return is available in closed form — `s · (φ + φ² + φ³)`
for a last step `s`. The load-bearing assertion correlates the model's predicted
median against *that*, not against realised prices, because a model can track
realised prices by luck and cannot track the true conditional mean by luck.

Two controls sit either side of it:

* a **random walk**, where the model must fail to beat persistence. A test suite
  that only demonstrates success cannot tell a working evaluation from a
  flattering one.
* **determinism**, because a fit that produces different weights each run cannot
  be compared with anything, including itself.

**What this does not show.** Every series is synthetic and generated by a process
this file wrote. Passing proves the pipeline can learn a structure that is
genuinely there; it says nothing about markets. `docs/OLYMPUS_NATIVE_MODEL_STATUS.md`
is the ledger, and blocker B1 — no reachable market data — is why.
"""

