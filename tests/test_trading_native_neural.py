def test_mismatched_weights_are_refused_rather_than_loaded(fitted):
    """A silent shape mismatch is a model producing plausible numbers from the
    wrong parameters."""
    parameters = dict(fitted.checkpoint.parameters)
    broken = {k: dict(v) for k, v in parameters["trunk_weights"].items()}
    name = sorted(broken)[0]
    broken[name] = {"shape": [99, 99], "values": [0.0] * (99 * 99)}
    parameters["trunk_weights"] = broken
    with pytest.raises(ConfigurationError) as exc:
        N.NeuralQuantileModel.from_parameters(parameters)
    assert "wrong shape" in str(exc.value)


def test_the_neural_forecaster_serves_through_the_standard_interface(fitted):
    """The point of the estimator registry: the same `NativeForecaster` serves
    a statistical checkpoint and a neural one."""
    clock = FixedClock(START + timedelta(days=90))
    forecaster = F.NativeForecaster(fitted.checkpoint, clock=clock)
    assert forecaster.consumes_bars is True
    assert forecaster.required_bars == CONFIG.lookback

    window = bars(ar1_series())[:400]
    produced = forecaster.forecast(window[-CONFIG.lookback:],
                                   as_of=window[-1].ts_close)
    if produced.abstained:
        assert produced.failure_code == F.CODE_MODEL_DECLINED
        return
    assert produced.horizon == CONFIG.horizon
    assert len(produced.quantiles) == len(CONFIG.quantiles)
    assert produced.model_identity["owner"] == "olympus"
    assert 0.0 <= produced.uncertainty <= 1.0


def test_the_neural_forecaster_registers_beside_the_baselines(fitted):
    from olympus.trading.forecast import ForecastService, PersistenceForecaster
    clock = FixedClock(START + timedelta(days=90))
    service = ForecastService(clock=clock)
    service.register("persistence", PersistenceForecaster(horizon=3, clock=clock))
    service.register("olympus-native", F.NativeForecaster(fitted.checkpoint,
                                                          clock=clock))
    window = bars(ar1_series())[:400]
    for name in service.names:
        produced = service.run(name, candles=window[-CONFIG.lookback:],
                               as_of=window[-1].ts_close,
                               instrument_key=KEY, timeframe=TF)
        assert produced.model_version


