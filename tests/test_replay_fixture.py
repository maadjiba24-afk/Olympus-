def test_cli_fixture_flag_imports_then_replays(monkeypatch, capsys):
    """--fixture imports into the live MEMORY_DIR then hands the imported
    run_id to the existing replay path. The full-orchestrator replay of the
    mini fixture would diverge (it was recorded through _mini_pipeline, not
    Olympus._pipeline), so the replay entry is monkeypatched: this test covers
    the import+lookup+dispatch wiring, the real replay determinism is proven
    library-level above."""
    from olympus import cli, orchestrator
    seen = {}

    def _fake_replay(run_id):
        seen["run_id"] = run_id
        original = trace.load_run(run_id)
        assert original is not None                 # imported before replay
        return original, trace.Trace("replay", "shared"), []

    monkeypatch.setattr(orchestrator, "replay_run", _fake_replay)
    rc = cli.main(["replay", "--fixture", str(MINI_FIXTURE)])
    out = capsys.readouterr().out
    manifest = json.loads((MINI_FIXTURE / "manifest.json").read_text())
    assert (rc or 0) == 0
    assert seen["run_id"] == manifest["run_id"]
    assert "Imported fixture run" in out and "byte-identically" in out


